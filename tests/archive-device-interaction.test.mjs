import test from 'node:test';
import assert from 'node:assert/strict';
import {fresh, extractSuggestion} from '../lib/engine.js';
import {readArchive,updateArchive} from '../lib/group-archive.js';
import {groupMemoryGraph} from '../lib/group-memory-demo.js';
import {deviceDialog} from '../lib/device-dialog.js';
import {approve,initDevices} from '../lib/devices.js';

test('group inbox batches source messages once and preserves old and new evidence across reload', ()=>{
  const scene=fresh('project'), other=fresh('course');
  updateArchive(scene);
  const initial=readArchive(scene).processed.length;
  for(const text of ['通知：原型演示：周五下午','更正：原型演示：周三下午','撤销：原型演示']) extractSuggestion(scene,text,'负责人');
  assert.equal(scene.messages.length-initial,3);
  const saved=JSON.parse(JSON.stringify(scene));
  const archive=updateArchive(saved);
  assert.deepEqual(archive.lastRefresh.changes.map(c=>c.action),['add','correct','revoke']);
  const versions=archive.memories.filter(m=>m.key==='notice:原型演示');
  assert.deepEqual(versions.map(m=>m.status),['superseded','revoked']);
  assert.equal(versions[0].changedBy,versions[1].evidence);
  assert.equal(versions[1].previous,versions[0].id);
  assert.ok(saved.messages.some(m=>m.id===versions[1].changedBy));
  assert.equal(updateArchive(saved),archive);
  assert.equal(readArchive(other).processed.length,0);
  extractSuggestion(saved,'撤销：别人的通知','成员');
  extractSuggestion(saved,'我喜欢先看图','成员');
  assert.deepEqual(updateArchive(saved).lastRefresh.changes.map(c=>c.action),['add']);
  for(const text of ['通知：分享会：周五','更正：分享会改到周三','分享会取消']) extractSuggestion(saved,text,'负责人');
  assert.deepEqual(updateArchive(saved).lastRefresh.changes.map(c=>c.action),['add','correct','revoke']);
  for(const m of saved.messages) assert.ok(groupMemoryGraph({...saved,...saved.groupArchive}).nodes.some(n=>n.messageId===m.id));
});
test('owner device lookup, rename and confirmation share the simulated registry',async()=>{
  const s=fresh('home'), dev=initDevices(s);
  assert.match((await deviceDialog(s,'我能控制多少台设备')).text,/5 台.*4 台/);
  assert.match((await deviceDialog(s,'light1是什么')).text,/客厅灯/);
  assert.match((await deviceDialog(s,'以后我说 light1，就是客厅灯')).text,/已记住/);
  const pending=await deviceDialog(s,'帮我打开 light1');
  assert.equal(dev.registry[0].state.on,false);
  const result=await approve(s,pending.entryId);
  assert.equal(result.receipt.state.on,true);
  assert.equal(await approve(s,pending.entryId),null);
  assert.match((await deviceDialog(s,'light1开着吗')).text,/已开启/);
  await deviceDialog(s,'以后客厅灯改叫阅读灯，light1 这个名字不用了');
  const restored=JSON.parse(JSON.stringify(s));
  assert.ok((await deviceDialog(restored,'帮我关闭 light1')).choices);
  assert.match((await deviceDialog(restored,'阅读灯是什么')).text,/客厅灯/);
  const followup=await deviceDialog(restored,'帮我关闭 light1','living_light');
  assert.ok(followup.entryId);
  assert.equal(await deviceDialog(s,'笔名是什么'),null);
  assert.equal(restored.devices.registry[0].state.on,true);
});
